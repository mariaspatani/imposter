-- ── 6. shuffle_lock ───────────────────────────────────────────────────────────
-- Prevents accidental re-shuffle after event starts.
-- Coordinator must explicitly unlock before re-shuffling.
CREATE TABLE IF NOT EXISTS shuffle_lock (
    id          INTEGER      PRIMARY KEY DEFAULT 1,  -- only one row
    is_locked   BOOLEAN      NOT NULL DEFAULT FALSE,
    locked_at   TIMESTAMPTZ,
    locked_by   TEXT,
    CONSTRAINT  single_row CHECK (id = 1)
);

INSERT INTO shuffle_lock (id, is_locked) VALUES (1, FALSE)
ON CONFLICT (id) DO NOTHING;

-- ── 7. event_timers ───────────────────────────────────────────────────────────
-- Authoritative server-side timer table.
