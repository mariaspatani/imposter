-- ── 1. teams ──────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS teams (
    id         SERIAL       PRIMARY KEY,
    team_name  TEXT         NOT NULL UNIQUE,
    team_code  TEXT         NOT NULL UNIQUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ── 2. participants ───────────────────────────────────────────────────────────
-- id is a UUID generated by Supabase (gen_random_uuid()).
CREATE TABLE IF NOT EXISTS participants (
    id               UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    team_id          INTEGER      NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    participant_name TEXT         NOT NULL,
    player_role      TEXT,          -- 'Imposter' | 'Specialist' | NULL (pre-shuffle)
    shuffle_group    TEXT,          -- 'Group 1' … 'Group 6' | NULL (pre-shuffle)
    is_imposter      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_participants_team_id ON participants (team_id);

